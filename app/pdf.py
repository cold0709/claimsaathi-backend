import logging
import os
from datetime import datetime
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from .policies import POLICIES
from .schemas import ClaimRequest

logger = logging.getLogger("claimsaathi.pdf")


def _font() -> str:
    path = os.getenv("PDF_FONT_PATH")
    if path and os.path.exists(path):
        try:
            pdfmetrics.registerFont(TTFont("CSFont", path))
            return "CSFont"
        except Exception:
            logger.exception("Could not load PDF_FONT_PATH")
    return "Helvetica"


def build_claim_pdf(body: ClaimRequest, v: dict, tracking_id: str | None = None) -> bytes:
    font = _font()
    policy = POLICIES[body.policy_id]
    bill = body.bill

    def t(s) -> str:
        """Escape for reportlab markup; Helvetica can't render non-Latin so degrade gracefully."""
        s = str(s if s is not None else "")
        if font == "Helvetica":
            s = s.encode("latin-1", "replace").decode("latin-1")
        return escape(s)

    def rs(x) -> str:   # ₹ is not in the standard PDF fonts
        return f"Rs. {x:,.2f}"

    ss = getSampleStyleSheet()
    base = ParagraphStyle("b", parent=ss["Normal"], fontName=font, fontSize=9.5, leading=13)
    h1 = ParagraphStyle("h1", parent=base, fontSize=18, leading=22, textColor=colors.HexColor("#14532d"))
    h2 = ParagraphStyle("h2", parent=base, fontSize=12, leading=16, spaceBefore=10, spaceAfter=4,
                        textColor=colors.HexColor("#14532d"))
    small = ParagraphStyle("s", parent=base, fontSize=8, textColor=colors.grey)

    def table(rows, widths, header=False):
        tb = Table([[Paragraph(t(c), base) for c in r] for r in rows], colWidths=widths)
        style = [("GRID", (0, 0), (-1, -1), 0.4, colors.lightgrey), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                 ("BACKGROUND", (0, 0), (0, -1) if not header else (-1, 0), colors.HexColor("#ecfdf5"))]
        tb.setStyle(TableStyle(style))
        return tb

    s = []
    s.append(Paragraph("ClaimSaathi - Insurance Claim Summary", h1))
    meta = f"Generated on {datetime.now():%d %b %Y, %H:%M}"
    if tracking_id:
        meta += f" | Tracking ID: {tracking_id}"
    s.append(Paragraph(t(meta), small))

    s.append(Paragraph("Policy & patient details", h2))
    s.append(table([
        ["Policy type", policy["name"]],
        ["Policy holder", body.policy_holder_name or "-"],
        ["Patient name", bill.patient_name or "-"],
        ["Hospital", bill.hospital or "-"],
        ["Admission date", bill.admission_date or "-"],
        ["Discharge date", bill.discharge_date or "-"],
        ["Diagnosis / reason", bill.diagnosis or "-"],
    ], [45 * mm, 125 * mm]))

    s.append(Paragraph("Bill items", h2))
    rows = [["Item", "Amount"]] + [[i.name, rs(i.amount)] for i in bill.items]
    rows.append(["Total on bill", rs(bill.total_amount or sum(i.amount for i in bill.items))])
    s.append(table(rows, [125 * mm, 45 * mm], header=True))

    s.append(Paragraph("Claim assessment", h2))
    s.append(table([
        ["Amount likely covered", rs(v["covered_amount"])],
        ["Amount not covered", rs(v["non_covered_amount"])],
        ["Claim readiness score", f"{v['readiness_score']} / 100"],
    ], [60 * mm, 110 * mm]))
    if v["non_covered_items"]:
        s.append(Spacer(1, 4))
        s.append(table([["Not covered", "Amount", "Reason"]] +
                       [[i["name"], rs(i["amount"]), i["reason"]] for i in v["non_covered_items"]],
                       [55 * mm, 30 * mm, 85 * mm], header=True))

    s.append(Paragraph("Documents checklist", h2))
    s.append(table([[d["name"], "Provided" if d["status"] == "provided" else "MISSING"] for d in v["documents"]],
                   [110 * mm, 60 * mm]))

    if v["warnings"]:
        s.append(Paragraph("Points to fix before submitting", h2))
        for w in v["warnings"]:
            s.append(Paragraph("• " + t(w["message_en"]), base))

    s.append(Spacer(1, 18))
    s.append(Paragraph("Declaration: I declare that the information given above is true and correct to the best "
                       "of my knowledge.", base))
    s.append(Spacer(1, 28))
    s.append(Paragraph("Signature of claimant: ______________________&nbsp;&nbsp;&nbsp; Date: ______________", base))
    s.append(Spacer(1, 12))
    s.append(Paragraph("Generated by ClaimSaathi. This is a claim-preparation summary, not an insurer-issued "
                       "document; amounts are estimates until the insurer settles the claim.", small))

    buf = BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                      bottomMargin=16 * mm, title="ClaimSaathi claim summary").build(s)
    return buf.getvalue()